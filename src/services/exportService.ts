import { Task, Sprint, Project, RiskPrediction, SavedReport, ReportKPICard } from '../types';

export interface ExportReportData {
  title: string;
  project: Project;
  sprint: Sprint;
  tasks: Task[];
  risks: RiskPrediction[];
  kpis?: ReportKPICard[];
  generatedBy: string;
  notes?: string;
}

/**
 * Generates and triggers browser download for formatted CSV files.
 */
export function exportToCSV(data: ExportReportData, filename?: string) {
  const name = filename || `${data.project.key}-${data.sprint.name.toLowerCase().replace(/\s+/g, '-')}-report.csv`;

  const rows: string[][] = [
    ['AGILEPULSE AI REPORT EXPORT'],
    ['Title', data.title],
    ['Project', `${data.project.name} (${data.project.key})`],
    ['Sprint', data.sprint.name],
    ['Sprint Health Score', `${data.sprint.healthScore} / 100`],
    ['Generated Date', new Date().toISOString()],
    ['Generated By', data.generatedBy],
    [],
    ['KPI SUMMARY'],
    ['Metric', 'Value', 'Status'],
    ['Completed Points', `${data.sprint.completedPoints} / ${data.sprint.totalPoints}`, 'Optimal'],
    ['Health Score', `${data.sprint.healthScore}`, data.sprint.healthScore > 80 ? 'Optimal' : 'Warning'],
    ['Blocked Tasks', `${data.tasks.filter((t) => t.blocked).length}`, 'Attention Required'],
    [],
    ['TASK LIST'],
    ['Task ID', 'Title', 'Story Points', 'Status', 'Priority', 'Blocked', 'Blocker Reason', 'Risk Level'],
  ];

  data.tasks.forEach((t) => {
    rows.push([
      t.id,
      `"${t.title.replace(/"/g, '""')}"`,
      t.storyPoints.toString(),
      t.status,
      t.priority,
      t.blocked ? 'YES' : 'NO',
      `"${(t.blockerReason || '').replace(/"/g, '""')}"`,
      t.riskLevel,
    ]);
  });

  rows.push([]);
  rows.push(['IDENTIFIED AI RISKS']);
  rows.push(['Category', 'Risk Title', 'Risk Level', 'Score', 'Impact Description']);

  data.risks.forEach((r) => {
    rows.push([
      r.category,
      `"${r.title.replace(/"/g, '""')}"`,
      r.level,
      r.riskScore.toString(),
      `"${r.description.replace(/"/g, '""')}"`,
    ]);
  });

  const csvContent = rows.map((r) => r.join(',')).join('\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', name);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

